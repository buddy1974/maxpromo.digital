/**
 * lib/os-i18n/dictionary.ts
 *
 * Translation dictionary for the AUTHENTICATED OS interface
 * (app/os/login + app/os/(protected)/**) — login, sidebar, layout chrome,
 * dashboard, clients, invoices, Angebote, jobs, leads, inbox, newsletter.
 *
 * This is a DIFFERENT axis of translation from lib/documents/labels.ts:
 *   - lib/documents/labels.ts   → the LANGUAGE OF A DOCUMENT (invoice /
 *                                  Angebot PDF + email), stored per record
 *                                  (os_invoices.language, os_angebote.language).
 *   - lib/os-i18n/dictionary.ts → the LANGUAGE OF THE OS UI ITSELF
 *                                  (nav, buttons, tables), a per-browser
 *                                  preference independent of any document.
 *
 * The two axes are orthogonal: a German OS can hold an English invoice and
 * vice versa. Nothing in this file may be used to render a document —
 * document rendering goes through getLabels(document.language).
 *
 * The public marketing site (app/[locale]/**) uses next-intl with
 * URL-segment routing. /os and /api/os are deliberately excluded from that
 * middleware (see middleware.ts) — the OS is a single authenticated app
 * shell, not a set of locale-prefixed routes — so this dictionary is
 * consumed via a client Context + cookie instead (see ./context.tsx).
 *
 * ARCHITECTURE RULE: this is the ONLY OS translation source. No inline
 * `locale === 'en' ? … : …` ternaries in components — add keys here.
 */

